def unflatten_dict(flat):
    nested = {}
    for k, v in flat.items():
        parts = k.split(".")
        cur = nested
        for part in parts[:-1]:
            cur = cur.setdefault(part, {})
        cur[parts[-1]] = v
    return nested

def flatten_dict(d, prefix=""):
    flat = {}
    for k, v in d.items():
        curr_key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            flat.update(flatten_dict(v, curr_key))
        elif isinstance(v, str):
            flat[curr_key] = v
    return flat

def main():
    print("Populating new keys for 22 Indic languages...")
    
    # Load translation cache
    cache = {}
    if CACHE_FILE.exists():
        cache = json.loads(CACHE_FILE.read_text(encoding="utf-8"))

    # Load canonical en.json
    en_dict = json.loads(EN_FILE.read_text(encoding="utf-8"))
    flat_en = flatten_dict(en_dict)

    for lang in TARGET_LANGUAGES:
        lang_file = LOCALES_DIR / f"{lang}.json"
        if not lang_file.exists():
            print(f"Warning: {lang_file} does not exist!")
            continue
            
        lang_dict = json.loads(lang_file.read_text(encoding="utf-8"))
        flat_lang = flatten_dict(lang_dict)

        updated_count = 0
        for key, lang_map in NEW_KEYS_DATA.items():
            if lang in lang_map:
                translated_text = lang_map[lang]
                flat_lang[key] = translated_text
                updated_count += 1
                
                # Cache entry
                source_text = flat_en.get(key, "")
                if source_text:
                    cache_key = hashlib.sha256((source_text + lang).encode("utf-8")).hexdigest()
                    cache[cache_key] = translated_text

        # Ensure all flat_en keys exist
        for key, val in flat_en.items():
            if key not in flat_lang:
                flat_lang[key] = val

        nested_lang = unflatten_dict(flat_lang)
        lang_file.write_text(json.dumps(nested_lang, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"[{lang}] Updated {updated_count} keys. Total keys: {len(flat_lang)}")

    CACHE_FILE.write_text(json.dumps(cache, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Done! Cache updated.")

if __name__ == "__main__":
    main()
